<?php
/**
 * Duplicate-submission gate (ORDER_WORKFLOW section 6). The first request
 * with a key creates a uniquely named option (add_option() fails if it
 * already exists, which makes the claim atomic in the database); every
 * later request with the same key gets "in progress" or the order already
 * created. Rows are not autoloaded and are cleaned up by a daily event.
 *
 * Value: "processing:<unix time>" or "done:<order id>:<unix time>".
 *
 * @package DecoStore
 */

namespace DecoStore\Orders;

defined( 'ABSPATH' ) || exit;

/**
 * Idempotency keys.
 */
class Idempotency {

	const PREFIX    = 'ds_idem_';
	const STALE     = 120;    // Seconds after which an unfinished claim may be taken over.
	const KEEP_DAYS = 2;

	/**
	 * Is the key well formed? (22-64 URL-safe characters, generated by the page.)
	 *
	 * @param mixed $key Key.
	 * @return bool
	 */
	public static function valid_key( $key ) {
		return is_string( $key ) && (bool) preg_match( '/^[A-Za-z0-9_-]{22,64}$/', $key );
	}

	/**
	 * Option name for a key.
	 *
	 * @param string $key Key.
	 * @return string
	 */
	private static function option( $key ) {
		return self::PREFIX . substr( hash( 'sha256', $key ), 0, 40 );
	}

	/**
	 * Try to claim a key.
	 *
	 * @param string   $key       Key.
	 * @param int      $now       Unix time.
	 * @param callable $has_order Callback( $key ): int order id carrying the key, 0 if none.
	 * @return array{state:string,order_id:int} state: claimed | in_progress | done.
	 */
	public static function claim( $key, $now, $has_order ) {
		$name = self::option( $key );
		if ( add_option( $name, 'processing:' . (int) $now, '', 'no' ) ) {
			return array(
				'state'    => 'claimed',
				'order_id' => 0,
			);
		}
		wp_cache_delete( $name, 'options' );
		wp_cache_delete( 'notoptions', 'options' );
		$value = (string) get_option( $name, '' );
		if ( preg_match( '/^done:(\d+):/', $value, $m ) ) {
			return array(
				'state'    => 'done',
				'order_id' => (int) $m[1],
			);
		}
		if ( preg_match( '/^processing:(\d+)$/', $value, $m ) && $now - (int) $m[1] > self::STALE ) {
			// A request died midway. If an order carries the key it was created: finish the record.
			$order_id = (int) call_user_func( $has_order, $key );
			if ( $order_id ) {
				self::complete( $key, $order_id, $now );
				return array(
					'state'    => 'done',
					'order_id' => $order_id,
				);
			}
			// Take over only if nobody else did in the meantime (compare-and-set on the old value).
			global $wpdb;
			$updated = $wpdb->update(
				$wpdb->options,
				array( 'option_value' => 'processing:' . (int) $now ),
				array(
					'option_name'  => $name,
					'option_value' => $value,
				)
			); // phpcs:ignore WordPress.DB.DirectDatabaseQuery -- Atomic compare-and-set; options API has none.
			wp_cache_delete( $name, 'options' );
			if ( 1 === $updated ) {
				return array(
					'state'    => 'claimed',
					'order_id' => 0,
				);
			}
		}
		return array(
			'state'    => 'in_progress',
			'order_id' => 0,
		);
	}

	/**
	 * Record the created order.
	 *
	 * @param string $key      Key.
	 * @param int    $order_id Order id.
	 * @param int    $now      Unix time.
	 * @return void
	 */
	public static function complete( $key, $order_id, $now ) {
		update_option( self::option( $key ), 'done:' . (int) $order_id . ':' . (int) $now, 'no' );
	}

	/**
	 * Release a claim after a failure so the customer can retry with the same key.
	 *
	 * @param string $key Key.
	 * @return void
	 */
	public static function release( $key ) {
		delete_option( self::option( $key ) );
	}

	/**
	 * Delete rows older than KEEP_DAYS (daily event).
	 *
	 * @param int $now Unix time.
	 * @return int Rows deleted.
	 */
	public static function cleanup( $now ) {
		global $wpdb;
		$rows    = $wpdb->get_results( $wpdb->prepare( "SELECT option_name, option_value FROM {$wpdb->options} WHERE option_name LIKE %s LIMIT 5000", $wpdb->esc_like( self::PREFIX ) . '%' ) ); // phpcs:ignore WordPress.DB.DirectDatabaseQuery -- Prefix scan of our own rows.
		$deleted = 0;
		foreach ( (array) $rows as $row ) {
			if ( preg_match( '/(\d+)$/', (string) $row->option_value, $m ) && $now - (int) $m[1] > self::KEEP_DAYS * DAY_IN_SECONDS ) {
				delete_option( $row->option_name );
				++$deleted;
			}
		}
		return $deleted;
	}
}
